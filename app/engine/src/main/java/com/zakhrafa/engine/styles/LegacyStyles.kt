        val keys = "ضصثقفغعهخحجشسيبلاتنمكطئؤظذدزروة".map(Char::toString)
        val values = chars.split("-")
        val m = mutableMapOf<String, String>()
        for (i in 0 until minOf(keys.size, values.size)) {
            m[keys[i]] = values[i]
        }
        return m
    }

