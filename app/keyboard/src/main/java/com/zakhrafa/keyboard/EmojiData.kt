    private val recentPrefs get() = "emoji_recent"

    fun getRecent(svc: ZakhrafaKeyboardService): List<String> {
        val prefs = svc.getSharedPreferences(recentPrefs, android.content.Context.MODE_PRIVATE)
        return (prefs.getString("recent", "") ?: "").split(",").filter { it.isNotEmpty() }
    }

    fun addRecent(svc: ZakhrafaKeyboardService, emoji: String) {
        val prefs = svc.getSharedPreferences(recentPrefs, android.content.Context.MODE_PRIVATE)
        val recent = getRecent(svc).toMutableList()
        recent.remove(emoji)
        recent.add(0, emoji)
        while (recent.size > 40) recent.removeAt(recent.lastIndex)
        prefs.edit().putString("recent", recent.joinToString(",")).apply()
    }

